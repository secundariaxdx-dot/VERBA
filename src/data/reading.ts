/** Builds an mcq Question; `notes` explain the wrong options in the order they appear. */
const mk =
  (prefix: string, level: Level, theme: ContentTopic) =>
  (
    n: number,
    topic: Topic,
    prompt: string,
    options: string[],
    correct: number,
    notes: string[],
    explanation: string,
    explanationEs: string,
  ): Question => {
    const optionNotes: Record<string, string> = {};
    let k = 0;
    options.forEach((o, i) => {
      if (i !== correct) optionNotes[o] = notes[k++];
    });
    return {
      id: `${prefix}-q${n}`,
      skill: "reading",
      topic,
      level,
      kind: "mcq",
      prompt,
      options,
      answers: [options[correct]],
      explanation,
      explanationEs,
      optionNotes,
      theme,
    };
  };

